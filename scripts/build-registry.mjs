#!/usr/bin/env bun
/*
 * Generates `src/__registry__/components.js` from the demo examples under
 * `src/lib/registry/examples/<slug>/*.svelte`, mirroring shadcn-svelte's
 * `scripts/build-registry.ts` -> `src/__registry__/index.js`.
 *
 * The demo app reads the generated `componentDemos` map (ordered example list
 * per component) and `slugsWithDemos` set. Re-run after adding/removing an
 * example:  bun run scripts/build-registry.mjs
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const examplesDir = resolve(root, 'src/lib/registry/examples');
const outDir = resolve(root, 'src/__registry__');
const outFile = resolve(outDir, 'components.js');

const slugs = readdirSync(examplesDir)
	.filter((name) => statSync(resolve(examplesDir, name)).isDirectory())
	.sort();

/** @type {Record<string, Array<{ path: string; key: string }>>} */
const componentDemos = {};

for (const slug of slugs) {
	const files = readdirSync(resolve(examplesDir, slug))
		.filter((f) => f.endsWith('.svelte'))
		.sort();
	if (files.length === 0) continue;
	componentDemos[slug] = files.map((file) => ({
		// Must match the keys produced by `import.meta.glob('/src/lib/registry/examples/**/*.svelte')`.
		path: `/src/lib/registry/examples/${slug}/${file}`,
		key: file.replace(/\.svelte$/, ''),
	}));
}

const header =
	'// This file is autogenerated by scripts/build-registry.mjs\n' +
	'// Do not edit this file directly. Run `bun run scripts/build-registry.mjs`.\n\n';

const body =
	`export const componentDemos = ${JSON.stringify(componentDemos, null, '\t')};\n\n` +
	'export const slugsWithDemos = new Set(Object.keys(componentDemos));\n';

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, header + body);

const demoCount = Object.values(componentDemos).reduce((n, list) => n + list.length, 0);
console.log(`build-registry: ${Object.keys(componentDemos).length} components, ${demoCount} demos -> ${outFile}`);
